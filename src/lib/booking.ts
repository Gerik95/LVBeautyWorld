/** One Salonkee treatment. The public checkout has no employee parameter. */
export const salonCheckout = (serviceId: number) => `${checkout}?serviceID=${serviceId}`;

/**
 * The booking step that lists every treatment in one salon category.
 * `search` is Salonkee's category slug (`urlPath`), for example `friseure`.
 * `goTo=services` scrolls that list into view; Salonkee then drops the parameter.
 */
export const salonCategoryList = (search: string) => {
  const url = new URL(`${salon}/widget/service`);
  url.searchParams.set("search", search);
  url.searchParams.set("goTo", "services");
  return url.toString();
};

